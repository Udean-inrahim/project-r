def muat_env():
    """Membaca .env sederhana tanpa dependensi tambahan."""
    berkas = BASE_DIR / ".env"
    if not berkas.exists():
        return

    for baris in berkas.read_text(encoding="utf-8").splitlines():
        baris = baris.strip()
        if not baris or baris.startswith("#") or "=" not in baris:
            continue
        kunci, nilai = baris.split("=", 1)
        kunci = kunci.strip()
        nilai = nilai.strip().strip('"').strip("'")
        os.environ.setdefault(kunci, nilai)


muat_env()


def ambil_database_url():
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError(
            "DATABASE_URL belum diatur. Isi connection string Neon "
            "di environment variable atau berkas .env."
        )
    return url


class Baris(dict):
    """Hasil query yang bisa diakses lewat nama kolom maupun indeks."""

    def __getitem__(self, kunci):
        if isinstance(kunci, int):
            return tuple(self.values())[kunci]
        return super().__getitem__(kunci)


def buat_baris(cursor):
    if cursor.description is None:
        return lambda nilai: nilai

    nama_kolom = [kolom.name for kolom in cursor.description]

    def susun(nilai):
        return Baris(zip(nama_kolom, nilai))

    return susun


def terjemahkan(sql):
    """Mengubah placeholder '?' menjadi '%s' di luar string literal."""
    hasil = []
    dalam_kutip = False
    i = 0
    panjang = len(sql)

    while i < panjang:
        karakter = sql[i]

        if karakter == "'":
            if dalam_kutip and i + 1 < panjang and sql[i + 1] == "'":
                hasil.append("''")
                i += 2
                continue
            dalam_kutip = not dalam_kutip
            hasil.append(karakter)
        elif karakter == "?" and not dalam_kutip:
            hasil.append("%s")
        else:
            hasil.append(karakter)

        i += 1

    return "".join(hasil)


class Koneksi:
    """Adapter tipis supaya pemakaian conn.execute() tetap sama seperti sqlite3."""

    def __init__(self, koneksi):
        self._koneksi = koneksi

    def execute(self, sql, params=()):
        return self._koneksi.execute(terjemahkan(sql), params or None)

    def commit(self):
        self._koneksi.commit()

    def rollback(self):
        self._koneksi.rollback()

    def close(self):
        self._koneksi.close()


def get_db_connection():
    if psycopg is None:
        raise RuntimeError(
            f"Modul psycopg tidak tersedia: {GALAT_PSYCOPG}"
        )

    koneksi = psycopg.connect(
        ambil_database_url(),
        row_factory=buat_baris,
        connect_timeout=15,
    )
    return Koneksi(koneksi)


