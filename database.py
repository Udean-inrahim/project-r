def ada_nilai_tersimpan(conn, kondisi, params=()):
    """Cek apakah ada nilai tersimpan untuk kondisi periode/siswa tertentu.

    Parameters
    ----------
    conn : Koneksi
        Active database connection wrapper.
    kondisi : str
        SQL WHERE condition (without WHERE keyword) referencing
        ``p.<kolom>`` (periode_akademik) or ``ps.<kolom>`` (periode_siswa).
    params : tuple
        Parameters for the condition placeholders.

    Returns
    -------
    bool
        True jika ada nilai tersimpan (penghapusan harus diblokir).
    """
    query = f"""
            SELECT 1
            FROM periode_akademik p
            JOIN periode_siswa ps ON ps.id_periode = p.id_periode
            LEFT JOIN nilai_tugas nt
                ON nt.id_periode_siswa = ps.id_periode_siswa
            LEFT JOIN nilai_tugas_rata_rata ntr
                ON ntr.id_periode_siswa = ps.id_periode_siswa
            LEFT JOIN nilai_komponen nk
                ON nk.id_periode_siswa = ps.id_periode_siswa
            WHERE {kondisi}
              AND (
                  nt.nilai IS NOT NULL
                  OR ntr.nilai IS NOT NULL
                  OR nk.nilai_uts IS NOT NULL
                  OR nk.nilai_uas IS NOT NULL
                  OR nk.nilai_kehadiran IS NOT NULL
              )
            LIMIT 1
        """
    return conn.execute(query, params).fetchone() is not None


def buat_tabel():
    conn = get_db_connection()

    try:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS schema_meta (
                versi INTEGER NOT NULL
            )
        """)

        versi_row = conn.execute("""
            SELECT versi
            FROM schema_meta
            ORDER BY versi DESC
            LIMIT 1
        """).fetchone()

        versi = versi_row["versi"] if versi_row else 0

        if versi >= VERSI_SKEMA:
            conn.commit()
            return

        if versi == 0:
            migrasi_dasar(conn)
            versi = 2

        for target_versi, fungsi in MIGRASI:
            if versi < target_versi:
                fungsi(conn)
                versi = target_versi

        conn.execute("DELETE FROM schema_meta")
        conn.execute(
            "INSERT INTO schema_meta (versi) VALUES (?)",
            (VERSI_SKEMA,),
        )

        conn.commit()

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


